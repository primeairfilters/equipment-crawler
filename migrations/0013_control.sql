-- The admin page's side of the crawler (P19, D75; Q22). Tracforce's /admin page logs in as eq_admin (made by
-- setup/pg-admin.sh before this runs) and touches only this schema:
-- - control.brands: the brands the user wants. The page adds a brand (name only: the crawler finds the rest), pauses,
--   resumes or archives it ("remove": its manuals stay searchable), and sets its priority (higher runs first), monthly
--   AI budget and automatic host approval. It never deletes and never writes crawl_brand_id, which the crawler fills
--   when a run first takes the brand on.
-- - control.brand_status, control.host_decisions, control.runs: what the page shows. Views read with their owner's
--   rights, so eq_admin sees these rows and nothing else in crawl or kb.
-- Additive: a new schema, a table, views, grants and a backfill of the brands the crawler already has.
CREATE SCHEMA IF NOT EXISTS control;
GRANT USAGE ON SCHEMA control TO eq_runtime, eq_admin;

CREATE TABLE IF NOT EXISTS control.brands (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (name ~ '^[^[:space:]]+( [^[:space:]]+)*$'),  -- trimmed, single spaces
  name_key text COLLATE "C" GENERATED ALWAYS AS (lower(name)) STORED UNIQUE,  -- crawl.brands.name_key
  state text NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'paused', 'archived')),
  priority integer NOT NULL DEFAULT 0,
  monthly_budget_usd numeric(8,2) NOT NULL DEFAULT 5 CHECK (monthly_budget_usd >= 0),
  auto_hosts boolean NOT NULL DEFAULT true,
  note text NULL,
  added_by text NULL,
  created_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  crawl_brand_id integer NULL UNIQUE REFERENCES crawl.brands (id)
);

INSERT INTO control.brands (name, state, monthly_budget_usd, auto_hosts, added_by, crawl_brand_id)
SELECT b.name, CASE WHEN b.status = 'active' THEN 'active' ELSE 'paused' END, b.monthly_budget_usd, b.auto_hosts,
       'crawler', b.id
FROM crawl.brands b
WHERE NOT EXISTS (SELECT 1 FROM control.brands c WHERE c.crawl_brand_id = b.id OR c.name_key = b.name_key);

-- crawl_state: paused / archived (the user's), waiting (no run has taken it on yet), discovering (looking for where
-- it publishes), crawling (a start address not yet visited, pages queued or due), current. problems: the last finished run's "needs you" lines that
-- name the brand.
CREATE VIEW control.brand_status AS
SELECT c.id, c.name, c.state, c.priority, c.monthly_budget_usd, c.auto_hosts, c.note, c.added_by, c.created_at,
       CASE WHEN c.state <> 'active' THEN c.state
            WHEN b.id IS NULL THEN 'waiting'
            WHEN b.discovered_at IS NULL AND NOT EXISTS (SELECT 1 FROM crawl.start_urls s WHERE s.brand_id = b.id)
                 THEN 'discovering'
            WHEN EXISTS (SELECT 1 FROM crawl.start_urls s WHERE s.brand_id = b.id AND s.status = 'active'
                         AND NOT EXISTS (SELECT 1 FROM crawl.pages p WHERE p.brand_id = b.id AND p.url_sha = s.url_sha))
              OR EXISTS (SELECT 1 FROM crawl.pages p WHERE p.brand_id = b.id
                         AND (p.fetch_state = 'queued'
                              OR (p.next_check_at <= (now() AT TIME ZONE 'UTC') AND p.fetch_state IN ('fetched', 'failed'))))
                 THEN 'crawling'
            ELSE 'current' END AS crawl_state,
       (SELECT COUNT(DISTINCT u.document_id) FROM crawl.document_urls u
          JOIN crawl.pages p ON p.id = u.page_id JOIN kb.documents d ON d.id = u.document_id
         WHERE p.brand_id = b.id AND d.state = 'live' AND d.hidden_at IS NULL) AS manuals,
       (SELECT COUNT(*) FROM crawl.pages p WHERE p.brand_id = b.id AND p.fetch_state = 'queued') AS pages_waiting,
       (SELECT COALESCE(SUM(a.cost_usd), 0) FROM crawl.ai_calls a WHERE a.brand_id = b.id
         AND a.created_at >= date_trunc('month', now() AT TIME ZONE 'UTC')) AS spent_this_month,
       last.finished_at AS last_run_at,
       ARRAY(SELECT line FROM jsonb_array_elements_text(COALESCE(last.summary -> 'needs_you', '[]')) AS line
              WHERE line LIKE c.name || ' %' OR line LIKE c.name || ':%') AS problems
FROM control.brands c
LEFT JOIN crawl.brands b ON b.id = c.crawl_brand_id
LEFT JOIN LATERAL (SELECT r.finished_at, r.summary FROM crawl.runs r WHERE r.state = 'done'
                   ORDER BY r.finished_at DESC, r.id DESC LIMIT 1) last ON true;

CREATE VIEW control.host_decisions AS
SELECT c.id AS brand_id, c.name AS brand, h.host, h.state, h.decided_by, h.reason, h.decided_at, h.updated_at
FROM crawl.host_decisions h JOIN control.brands c ON c.crawl_brand_id = h.brand_id;

CREATE VIEW control.runs AS
SELECT id, started_at, finished_at, state, summary, report FROM crawl.runs;

GRANT SELECT, INSERT, UPDATE ON control.brands TO eq_runtime;
GRANT SELECT ON control.brand_status, control.host_decisions, control.runs TO eq_runtime;
GRANT SELECT ON control.brands, control.brand_status, control.host_decisions, control.runs TO eq_admin;
GRANT INSERT (name, state, priority, monthly_budget_usd, auto_hosts, note, added_by) ON control.brands TO eq_admin;
GRANT UPDATE (state, priority, monthly_budget_usd, auto_hosts, note) ON control.brands TO eq_admin;
