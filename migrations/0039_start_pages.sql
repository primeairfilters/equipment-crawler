-- Pages the user adds to crawl from the admin page's Hosts tab (user 2026-11-13). The page writes the brand and the
-- address; the next run's sync (crawler/control.py take_start_pages) makes it a start address of that brand, approves
-- its host for all its pages and records the user's host decision, so it shows on the Hosts tab like the crawler's
-- own. start_url_id and refused are the crawler's: refused keeps why an address was not taken. The page never
-- deletes. Additive: a new table, a view and grants.
CREATE TABLE IF NOT EXISTS control.start_pages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES control.brands (id),
  url text NOT NULL CHECK (url ~* '^https?://[^/[:space:]?#]+([/?#][^[:space:]]*)?$' AND length(url) <= 2048),
  added_by text NULL,
  created_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  start_url_id integer NULL REFERENCES crawl.start_urls (id),
  refused text NULL,
  UNIQUE (brand_id, url)
);

-- state: refused (the crawler would not take it), waiting (no run has taken it yet), crawled or failed (its page was
-- fetched, or tried and failed), crawling (taken, not fetched yet). host: the address's host, for the Hosts tab.
CREATE VIEW control.start_page_status AS
SELECT sp.id, sp.brand_id, c.name AS brand, sp.url,
       lower(substring(sp.url from '^[A-Za-z]+://(?:[^@/]*@)?([^/:?#]+)')) AS host,
       sp.added_by, sp.created_at, sp.refused,
       CASE WHEN sp.refused IS NOT NULL THEN 'refused'
            WHEN sp.start_url_id IS NULL THEN 'waiting'
            WHEN p.fetch_state = 'fetched' THEN 'crawled'
            WHEN p.fetch_state = 'failed' THEN 'failed'
            ELSE 'crawling' END AS state,
       p.fetched_at
FROM control.start_pages sp
JOIN control.brands c ON c.id = sp.brand_id
LEFT JOIN crawl.start_urls s ON s.id = sp.start_url_id
LEFT JOIN crawl.pages p ON p.brand_id = s.brand_id AND p.url_sha = s.url_sha;

GRANT SELECT, INSERT ON control.start_pages TO eq_runtime;
GRANT UPDATE (start_url_id, refused) ON control.start_pages TO eq_runtime;
GRANT SELECT ON control.start_page_status TO eq_runtime;
GRANT SELECT, INSERT (brand_id, url, added_by) ON control.start_pages TO eq_admin;
GRANT SELECT ON control.start_page_status TO eq_admin;
