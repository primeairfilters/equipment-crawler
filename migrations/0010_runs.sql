-- The nightly run (P17, D73): one row per `./crawl auto`, for the admin page (Q20) and the text report in
-- DOCS_DIR/.runs/. A run still 'running' when the next starts was stopped part way ('interrupted'). And a monthly AI
-- budget per brand (Q25: $5 by default; the admin page may change it, P19). Additive: a new table and a new column.
CREATE TABLE IF NOT EXISTS crawl.runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  finished_at timestamp without time zone NULL,
  state text NOT NULL CHECK (state IN ('running', 'done', 'skipped', 'interrupted')),
  summary jsonb NULL,
  report text NULL
);
ALTER TABLE crawl.brands ADD COLUMN IF NOT EXISTS monthly_budget_usd numeric(8,2) NOT NULL DEFAULT 5;
