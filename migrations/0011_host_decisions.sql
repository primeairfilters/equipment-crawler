-- Hosts the crawler approves itself (P18, D74; Q21). A host approved from the evidence of a brand's own pages gives
-- PDFs only (scope 'pdf'), never its web pages. Each judgment is kept with its reason: 'trial' (5 PDFs fetched and
-- tagged), then 'confirmed' (3 or more are equipment documents) or 'stopped'; 'rejected' when the AI said no. A brand's
-- auto_hosts switch (and AUTO_APPROVE_HOSTS=off for everything) turns it off. Additive: a column on brand_domains and
-- brands, and a new table.
ALTER TABLE crawl.brand_domains ADD COLUMN IF NOT EXISTS scope text NOT NULL DEFAULT 'all' CHECK (scope IN ('all', 'pdf'));
ALTER TABLE crawl.brands ADD COLUMN IF NOT EXISTS auto_hosts boolean NOT NULL DEFAULT true;
CREATE TABLE IF NOT EXISTS crawl.host_decisions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES crawl.brands (id),
  host text COLLATE "C" NOT NULL,
  state text NOT NULL CHECK (state IN ('trial', 'confirmed', 'stopped', 'rejected')),
  decided_by text NOT NULL CHECK (decided_by IN ('ai', 'rule', 'user')),
  reason text NOT NULL,
  evidence jsonb NULL,
  trial_pages bigint[] NOT NULL DEFAULT '{}',
  decided_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  updated_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  UNIQUE (brand_id, host)
);
