-- Breeze misses (P21, D77): when Breeze's search gives up, its tool writes a miss here: the question, and the brand,
-- model, equipment type and trade when a unit is known. Never customer names, addresses or job details (the tool's
-- side of the contract). eq_breeze may insert and nothing else: it cannot read, change or delete a miss, and its
-- read-only rights on kb are unchanged (a schema of its own, so kb stays the serving layer).
-- Each run sorts new misses (crawler/misses.py): uncovered_brand (the admin page lists it for the user), no_manual
-- (a gap-fill search for the model, then a crawl), search_missed (a manual has the answer: an eval question with its
-- page, and a search to tune), not_in_manuals (logged), repeat (of an earlier miss on the same model).
-- Additive: a new schema, a table, a view and grants.
CREATE SCHEMA IF NOT EXISTS breeze;
GRANT USAGE ON SCHEMA breeze TO eq_breeze, eq_runtime;

CREATE TABLE IF NOT EXISTS breeze.misses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asked_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  question text NOT NULL CHECK (length(question) BETWEEN 1 AND 2000),
  brand text NULL CHECK (length(brand) <= 200),
  model text NULL CHECK (length(model) <= 200),
  equipment_type text NULL CHECK (length(equipment_type) <= 100),
  trade text NULL CHECK (length(trade) <= 100),
  source text NOT NULL DEFAULT 'chat' CHECK (source IN ('chat', 'live_camera')),
  state text NOT NULL DEFAULT 'new' CHECK (state IN ('new', 'sorted')),
  kind text NULL CHECK (kind IN ('uncovered_brand', 'no_manual', 'search_missed', 'not_in_manuals', 'repeat')),
  detail jsonb NOT NULL DEFAULT '{}',
  repeat_of bigint NULL REFERENCES breeze.misses (id),
  sorted_at timestamp without time zone NULL
);
CREATE INDEX IF NOT EXISTS misses_state ON breeze.misses (state, id);

GRANT INSERT (question, brand, model, equipment_type, trade, source) ON breeze.misses TO eq_breeze;
GRANT SELECT, INSERT, UPDATE ON breeze.misses TO eq_runtime;

-- the admin page: what Breeze could not answer, sorted; uncovered brands are the user's to add (brands are the user's)
CREATE VIEW control.breeze_misses AS
SELECT id, asked_at, question, brand, model, equipment_type, trade, source, state, kind, detail, repeat_of, sorted_at
FROM breeze.misses;

GRANT SELECT ON control.breeze_misses TO eq_admin, eq_runtime;
