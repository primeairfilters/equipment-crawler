-- Documents uploaded by hand from the admin page (P19, D84). The page puts the file in the docs bucket's inbox/
-- folder (its own AWS user can do nothing else) and adds a row here; the next run (or `./crawl uploads`) takes it
-- through the crawled-PDF pipeline and writes the outcome back:
-- queued -> processing -> added (document_id) / already_had (the same file is stored: document_id) / rejected (reason).
-- manufacturer_id: the brand the user picked, else the one the text names most (user, 2026-10-29), else none (Breeze
-- still uses it for any question, D82). page_id: the crawler page row that carries the file through text and tagging.
-- Additive: a new table and grants.
CREATE TABLE IF NOT EXISTS control.uploads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  s3_key text COLLATE "C" NOT NULL UNIQUE CHECK (s3_key ~ '^inbox/[^/]+(/[^/]+)*$' AND s3_key !~ '(^|/)\.\.?(/|$)'),
  file_name text NOT NULL CHECK (length(file_name) BETWEEN 1 AND 255),
  brand_id integer NULL REFERENCES control.brands (id),
  note text NULL,
  uploaded_by text NULL,
  uploaded_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  state text NOT NULL DEFAULT 'queued' CHECK (state IN ('queued', 'processing', 'added', 'already_had', 'rejected')),
  reason text NULL,
  document_id bigint NULL REFERENCES kb.documents (id),
  manufacturer_id integer NULL REFERENCES kb.manufacturers (id),
  page_id bigint NULL UNIQUE REFERENCES crawl.pages (id),
  processed_at timestamp without time zone NULL
);
CREATE INDEX IF NOT EXISTS uploads_state ON control.uploads (state, id);

GRANT SELECT, INSERT, UPDATE ON control.uploads TO eq_runtime;
GRANT SELECT ON control.uploads TO eq_admin;
GRANT INSERT (s3_key, file_name, brand_id, note, uploaded_by) ON control.uploads TO eq_admin;
