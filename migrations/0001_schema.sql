-- Round 4 schema on PostgreSQL 18 + pgvector (D38, D64-D66). Additive only: every statement is safe to run twice.
-- crawl = the working layer (cold, the crawler's own). kb = the serving layer (hot, the only one eq_breeze can read).
-- kb tables have no foreign keys into crawl, so kb can be copied on its own (D47).
-- Times are UTC, stored without a time zone. Flags are booleans. Keys and codes use the C collation (D53).

CREATE SCHEMA IF NOT EXISTS crawl;
CREATE SCHEMA IF NOT EXISTS kb;

GRANT USAGE ON SCHEMA crawl, kb TO eq_runtime;
GRANT USAGE ON SCHEMA kb TO eq_breeze;
ALTER DEFAULT PRIVILEGES IN SCHEMA crawl GRANT SELECT, INSERT, UPDATE ON TABLES TO eq_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA kb GRANT SELECT, INSERT, UPDATE ON TABLES TO eq_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA kb GRANT SELECT ON TABLES TO eq_breeze;

-- ------------------------------------------------------------------ kb: manufacturers and models

CREATE TABLE IF NOT EXISTS kb.manufacturers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  name_key text COLLATE "C" NOT NULL UNIQUE,
  content_use text NULL CHECK (content_use IN ('quote', 'cite_only', 'off')),  -- NULL until Q10 is answered (D51)
  hidden_at timestamp NULL,
  hidden_reason text NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE IF NOT EXISTS kb.manufacturer_aliases (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  manufacturer_id integer NOT NULL REFERENCES kb.manufacturers (id),
  alias text NOT NULL,
  alias_key text COLLATE "C" NOT NULL UNIQUE,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS manufacturer_aliases_manufacturer ON kb.manufacturer_aliases (manufacturer_id);

CREATE TABLE IF NOT EXISTS kb.models (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  manufacturer_id integer NOT NULL REFERENCES kb.manufacturers (id),
  model_number text NOT NULL,
  model_key text COLLATE "C" NOT NULL,
  trade text NULL,
  equipment_type text NULL,
  is_base_model boolean NOT NULL DEFAULT false,
  energy_star_confirmed boolean NOT NULL DEFAULT false,
  hidden_at timestamp NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  UNIQUE (manufacturer_id, model_key)
);
CREATE INDEX IF NOT EXISTS models_model_key ON kb.models (model_key);
CREATE INDEX IF NOT EXISTS models_model_key_trgm ON kb.models USING gin (model_key gin_trgm_ops);
CREATE INDEX IF NOT EXISTS models_energy_star ON kb.models (manufacturer_id, energy_star_confirmed);

-- ------------------------------------------------------------------ kb: documents (one per unique PDF, D40)

CREATE TABLE IF NOT EXISTS kb.documents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_sha char(64) COLLATE "C" NOT NULL UNIQUE,
  manufacturer_id integer NULL REFERENCES kb.manufacturers (id),
  trade text NULL,
  equipment_type text NULL,
  doc_type text NULL,
  language text NULL,
  title text NULL,
  form_number text COLLATE "C" NULL,
  canonical_url text NULL,
  page_count integer NULL,
  text_pages integer NULL,
  needs_ocr boolean NOT NULL DEFAULT false,
  state text NOT NULL DEFAULT 'new' CHECK (state IN ('new', 'tagged', 'built', 'live', 'retired')),
  live_build integer NULL,
  replaces_id bigint NULL REFERENCES kb.documents (id),
  hidden_at timestamp NULL,
  hidden_reason text NULL,
  tagged_by text NULL,
  tagger_version text NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  updated_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS documents_form_number ON kb.documents (manufacturer_id, form_number);
CREATE INDEX IF NOT EXISTS documents_state ON kb.documents (state);
CREATE INDEX IF NOT EXISTS documents_replaces ON kb.documents (replaces_id);

CREATE TABLE IF NOT EXISTS kb.document_models (
  document_id bigint NOT NULL REFERENCES kb.documents (id),
  model_id bigint NOT NULL REFERENCES kb.models (id),
  model_key text COLLATE "C" NOT NULL,  -- copied from models so a prefix lookup is one index range (D49)
  manufacturer_id integer NOT NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  PRIMARY KEY (document_id, model_id)
);
CREATE INDEX IF NOT EXISTS document_models_key ON kb.document_models (model_key, document_id);

-- ------------------------------------------------------------------ kb: sections, terms, switches

CREATE TABLE IF NOT EXISTS kb.sections (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id bigint NOT NULL REFERENCES kb.documents (id),
  build integer NOT NULL,
  section_no integer NOT NULL,
  page_from integer NOT NULL,
  page_to integer NOT NULL,
  heading_path text NOT NULL DEFAULT '',
  kind text NOT NULL CHECK (kind IN ('text', 'table')),
  body text COMPRESSION lz4 NOT NULL,
  body_sha char(64) COLLATE "C" NOT NULL,
  token_count integer NOT NULL,
  flags text[] NOT NULL DEFAULT '{}',
  manufacturer_id integer NULL,  -- filters copied from the document (D48)
  trade text NULL,
  equipment_type text NULL,
  doc_type text NULL,
  language text NULL,
  is_live boolean NOT NULL DEFAULT false,
  sectioner_version text NOT NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  tsv tsvector GENERATED ALWAYS AS (to_tsvector('english'::regconfig, heading_path || ' ' || body)) STORED,
  UNIQUE (document_id, build, section_no)
);
CREATE INDEX IF NOT EXISTS sections_live_filter ON kb.sections (manufacturer_id, equipment_type) WHERE is_live;
CREATE INDEX IF NOT EXISTS sections_live_order ON kb.sections (document_id, section_no) WHERE is_live;
CREATE INDEX IF NOT EXISTS sections_live_tsv ON kb.sections USING gin (tsv) WHERE is_live;

CREATE TABLE IF NOT EXISTS kb.section_terms (
  term text COLLATE "C" NOT NULL,
  section_id bigint NOT NULL REFERENCES kb.sections (id),
  PRIMARY KEY (term, section_id)
);
CREATE INDEX IF NOT EXISTS section_terms_section ON kb.section_terms (section_id);

CREATE TABLE IF NOT EXISTS kb.visibility_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  target_type text NOT NULL CHECK (target_type IN ('document', 'manufacturer')),
  target_id bigint NOT NULL,
  hidden boolean NOT NULL,
  reason text NULL,
  by_whom text NOT NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);
CREATE INDEX IF NOT EXISTS visibility_log_target ON kb.visibility_log (target_type, target_id);

-- ------------------------------------------------------------------ kb: ENERGY STAR matched systems

CREATE TABLE IF NOT EXISTS kb.es_systems (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ahri_ref text COLLATE "C" NOT NULL,
  ratings_key char(64) COLLATE "C" NOT NULL,
  seer2 numeric(6,2) NULL,
  eer2 numeric(6,2) NULL,
  hspf2 numeric(6,2) NULL,
  cooling_capacity_btuh integer NULL,
  heating_capacity_btuh integer NULL,
  superseded boolean NOT NULL DEFAULT false,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  UNIQUE (ahri_ref, ratings_key)
);
CREATE INDEX IF NOT EXISTS es_systems_current ON kb.es_systems (ahri_ref, superseded);

CREATE TABLE IF NOT EXISTS kb.es_system_members (
  system_id bigint NOT NULL REFERENCES kb.es_systems (id),
  model_id bigint NOT NULL REFERENCES kb.models (id),
  role text NOT NULL,
  PRIMARY KEY (system_id, model_id, role)
);
CREATE INDEX IF NOT EXISTS es_system_members_model ON kb.es_system_members (model_id);

-- ------------------------------------------------------------------ crawl: brands, hosts, start addresses

CREATE TABLE IF NOT EXISTS crawl.brands (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  name_key text COLLATE "C" NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'stopped')),
  discovered_at timestamp NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE IF NOT EXISTS crawl.brand_domains (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES crawl.brands (id),
  host text COLLATE "C" NOT NULL,
  status text NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'approved', 'stopped')),
  found_by text NOT NULL CHECK (found_by IN ('ai', 'user')),
  evidence_url text NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  UNIQUE (brand_id, host)
);
CREATE INDEX IF NOT EXISTS brand_domains_host ON crawl.brand_domains (host);

CREATE TABLE IF NOT EXISTS crawl.start_urls (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES crawl.brands (id),
  url text NOT NULL,
  url_sha char(64) COLLATE "C" NOT NULL,
  found_by text NOT NULL CHECK (found_by IN ('discover', 'sitemap', 'user', 'gapfill')),
  kind text NOT NULL DEFAULT 'page' CHECK (kind IN ('page', 'feed')),  -- a feed is a JSON document API (D68b)
  depth smallint NOT NULL DEFAULT 3 CHECK (depth BETWEEN 0 AND 10),  -- D60
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'stopped')),
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  UNIQUE (brand_id, url_sha)
);

CREATE TABLE IF NOT EXISTS crawl.hosts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  host text COLLATE "C" NOT NULL UNIQUE,
  last_request_at timestamp NULL,
  next_allowed_at timestamp NULL,
  failure_count integer NOT NULL DEFAULT 0,
  rest_until timestamp NULL,
  robots_body text NULL,
  robots_status integer NULL,
  robots_fetched_at timestamp NULL,
  ignore_robots boolean NOT NULL DEFAULT false,  -- D67: the user's per-host switch, with when it was last changed
  ignore_robots_changed_at timestamp NULL,
  use_browser boolean NOT NULL DEFAULT false,  -- D68a: pages on this host are rendered in headless Chromium
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

-- ------------------------------------------------------------------ crawl: pages, text, links, runs

CREATE TABLE IF NOT EXISTS crawl.pages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES crawl.brands (id),
  host_id integer NOT NULL REFERENCES crawl.hosts (id),
  start_url_id integer NULL REFERENCES crawl.start_urls (id),
  parent_id bigint NULL,
  url text NOT NULL,
  url_sha char(64) COLLATE "C" NOT NULL,
  final_url text NULL,
  depth smallint NOT NULL DEFAULT 0,
  is_pdf boolean NOT NULL DEFAULT false,
  http_status integer NULL,
  content_type text NULL,
  etag text NULL,
  last_modified text NULL,
  server_date text NULL,
  content_sha char(64) COLLATE "C" NULL,
  fetched_at timestamp NULL,
  next_check_at timestamp NULL,
  fail_count integer NOT NULL DEFAULT 0,
  fetch_state text NOT NULL DEFAULT 'queued' CHECK (fetch_state IN (
    'queued', 'fetched', 'failed', 'refused', 'beyond_depth', 'over_limit', 'skipped_keyword', 'skipped_ai', 'ask_ai',
    'out_of_scope')),
  decision text NULL CHECK (decision IN ('crawl', 'skip')),
  decided_by text NULL CHECK (decided_by IN ('rule', 'ai', 'user')),
  decision_reason text NULL,
  page_count integer NULL,
  extraction_status text NOT NULL DEFAULT 'waiting' CHECK (extraction_status IN ('waiting', 'skipped', 'extracted', 'failed')),
  ai_extracted_sha char(64) COLLATE "C" NULL,
  ai_extractor_version text NULL,
  ai_batch_id text NULL,
  ai_pending_sha char(64) COLLATE "C" NULL,
  ai_parts integer NULL,
  ai_model text NULL,
  ai_reserved_usd numeric(12,6) NOT NULL DEFAULT 0,
  ai_retry_at timestamp NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  UNIQUE (brand_id, url_sha)
);
CREATE INDEX IF NOT EXISTS pages_host ON crawl.pages (host_id);
CREATE INDEX IF NOT EXISTS pages_parent ON crawl.pages (parent_id);
CREATE INDEX IF NOT EXISTS pages_next_check ON crawl.pages (next_check_at);
CREATE INDEX IF NOT EXISTS pages_extraction ON crawl.pages (extraction_status);
CREATE INDEX IF NOT EXISTS pages_content_sha ON crawl.pages (content_sha);
CREATE INDEX IF NOT EXISTS pages_ai_extracted_sha ON crawl.pages (ai_extracted_sha);
CREATE INDEX IF NOT EXISTS pages_ai_batch ON crawl.pages (ai_batch_id);
CREATE INDEX IF NOT EXISTS pages_fetch_state ON crawl.pages (brand_id, fetch_state);

CREATE TABLE IF NOT EXISTS crawl.page_text (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id bigint NOT NULL REFERENCES crawl.pages (id),
  page_number integer NOT NULL DEFAULT 1,
  title text NULL,
  text_sha char(64) COLLATE "C" NOT NULL,
  body text COMPRESSION lz4 NOT NULL,
  has_text boolean NOT NULL DEFAULT true,  -- false for a scanned page with no text layer (D59)
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  UNIQUE (page_id, page_number)
);
CREATE INDEX IF NOT EXISTS page_text_sha ON crawl.page_text (text_sha);

CREATE TABLE IF NOT EXISTS crawl.page_links (
  from_page_id bigint NOT NULL REFERENCES crawl.pages (id),
  to_page_id bigint NOT NULL REFERENCES crawl.pages (id),
  link_text text NULL,
  first_seen_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  PRIMARY KEY (from_page_id, to_page_id)
);
CREATE INDEX IF NOT EXISTS page_links_to ON crawl.page_links (to_page_id);

CREATE TABLE IF NOT EXISTS crawl.crawl_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  started_at timestamp NOT NULL,
  finished_at timestamp NULL,
  brand_id integer NOT NULL,
  start_url_id integer NOT NULL,
  pages_fetched integer NOT NULL DEFAULT 0,
  limit_hit boolean NOT NULL DEFAULT false,
  links_left integer NOT NULL DEFAULT 0,
  PRIMARY KEY (id, started_at)
) PARTITION BY RANGE (started_at);
CREATE INDEX IF NOT EXISTS crawl_runs_start ON crawl.crawl_runs (start_url_id, started_at);

CREATE TABLE IF NOT EXISTS crawl.crawl_keywords (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  keyword text COLLATE "C" NOT NULL,
  effect text NOT NULL CHECK (effect IN ('skip', 'prefer')),
  brand_id integer NULL REFERENCES crawl.brands (id),  -- NULL = every brand
  host text COLLATE "C" NULL,  -- set on learned folder rules: the rule covers this host's folder only (D62)
  active boolean NOT NULL DEFAULT true,
  source text NOT NULL CHECK (source IN ('user', 'learned')),
  note text NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  CONSTRAINT crawl_keywords_one_rule UNIQUE NULLS NOT DISTINCT (brand_id, host, keyword)
);
CREATE INDEX IF NOT EXISTS crawl_keywords_active ON crawl.crawl_keywords (active, brand_id);

-- ------------------------------------------------------------------ crawl: originals, where documents were found

CREATE TABLE IF NOT EXISTS crawl.files (
  sha256 char(64) COLLATE "C" PRIMARY KEY,
  size_bytes bigint NOT NULL,
  mime_type text NOT NULL,
  storage_key text NOT NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE IF NOT EXISTS crawl.document_urls (
  document_id bigint NOT NULL REFERENCES kb.documents (id),
  page_id bigint NOT NULL REFERENCES crawl.pages (id),
  url text NOT NULL,
  first_seen_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  last_seen_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  PRIMARY KEY (document_id, page_id)
);
CREATE INDEX IF NOT EXISTS document_urls_page ON crawl.document_urls (page_id);

-- ------------------------------------------------------------------ crawl: AI spend, gap-fill, ENERGY STAR rows

CREATE TABLE IF NOT EXISTS crawl.ai_calls (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  purpose text NOT NULL,
  brand_id integer NULL,
  page_id bigint NULL,
  model text NOT NULL,
  input_tokens integer NOT NULL DEFAULT 0,
  output_tokens integer NOT NULL DEFAULT 0,
  cache_read_tokens integer NOT NULL DEFAULT 0,
  cache_write_tokens integer NOT NULL DEFAULT 0,
  searches integer NOT NULL DEFAULT 0,
  is_batch boolean NOT NULL DEFAULT false,
  rejected boolean NOT NULL DEFAULT false,
  cost_usd numeric(12,6) NOT NULL,
  created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);
CREATE INDEX IF NOT EXISTS ai_calls_created ON crawl.ai_calls (created_at);
CREATE INDEX IF NOT EXISTS ai_calls_page ON crawl.ai_calls (page_id);

CREATE TABLE IF NOT EXISTS crawl.gapfill_searches (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES crawl.brands (id),
  family text COLLATE "C" NOT NULL,
  searched_at timestamp NOT NULL,
  found boolean NOT NULL DEFAULT false,
  UNIQUE (brand_id, family)
);

CREATE TABLE IF NOT EXISTS crawl.es_rows (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id text NOT NULL,
  row_id text NOT NULL,
  ahri_ref text COLLATE "C" NULL,
  brand_name text NULL,
  model_number text NULL,
  model_key text COLLATE "C" NULL,
  row_json text COMPRESSION lz4 NOT NULL,
  row_hash char(64) COLLATE "C" NOT NULL,
  system_id bigint NULL,
  first_seen_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  UNIQUE (dataset_id, row_id)
);
CREATE INDEX IF NOT EXISTS es_rows_ahri ON crawl.es_rows (ahri_ref);
CREATE INDEX IF NOT EXISTS es_rows_system ON crawl.es_rows (system_id);

CREATE TABLE IF NOT EXISTS crawl.es_state (
  dataset_id text PRIMARY KEY,
  rows_updated_at bigint NOT NULL,
  pulled_at timestamp NOT NULL
);

-- Tables made before the default privileges above (or by a re-run) get the same rights.
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA crawl TO eq_runtime;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA kb TO eq_runtime;
GRANT SELECT ON ALL TABLES IN SCHEMA kb TO eq_breeze;
