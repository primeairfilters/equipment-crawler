-- Coverage and gap filling (P20, D76; Q24). Each brand's public model list comes from the ENERGY STAR Model Index
-- (every certified product of every category: HVAC, water heaters, pool pumps, appliances, ice machines ...), pulled
-- once a month per brand. Coverage is how many of the brand's model families (crawler/gapfill.family) have a manual;
-- each run measures it, then fills gaps: a web search per uncovered family (gapfill, within its caps) and the brand
-- site's own search (a search form the crawler found on the brand's pages), at the polite rate. A brand whose round
-- found nothing new and has nothing left to search is in upkeep. Additive: new tables and a view.
CREATE TABLE IF NOT EXISTS crawl.public_models (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES crawl.brands (id),
  source text NOT NULL,
  list_id text COLLATE "C" NOT NULL,
  brand_name text NOT NULL,
  model_number text NOT NULL,
  model_key text COLLATE "C" NOT NULL,
  family text COLLATE "C" NOT NULL,
  category text NULL,
  product_type text NULL,
  first_seen_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  last_seen_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  UNIQUE (brand_id, source, list_id)
);
CREATE INDEX IF NOT EXISTS public_models_family ON crawl.public_models (brand_id, family);

CREATE TABLE IF NOT EXISTS crawl.public_model_pulls (
  brand_id integer NOT NULL REFERENCES crawl.brands (id),
  source text NOT NULL,
  pulled_at timestamp without time zone NOT NULL,
  rows_seen integer NOT NULL DEFAULT 0,
  status text NOT NULL,
  PRIMARY KEY (brand_id, source)
);

CREATE TABLE IF NOT EXISTS crawl.coverage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES crawl.brands (id),
  run_id bigint NULL REFERENCES crawl.runs (id),
  measured_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  families integer NOT NULL,
  covered integer NOT NULL,
  by_category jsonb NOT NULL DEFAULT '{}',
  new_documents integer NOT NULL DEFAULT 0,
  gap_searches integer NOT NULL DEFAULT 0,
  site_searches integer NOT NULL DEFAULT 0,
  phase text NOT NULL CHECK (phase IN ('no_public_list', 'filling_gaps', 'upkeep'))
);
CREATE INDEX IF NOT EXISTS coverage_brand ON crawl.coverage (brand_id, measured_at DESC);

CREATE TABLE IF NOT EXISTS crawl.site_search_templates (
  brand_id integer NOT NULL REFERENCES crawl.brands (id),
  host text COLLATE "C" NOT NULL,
  template text NOT NULL,
  found_on text NOT NULL,
  found_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  PRIMARY KEY (brand_id, host)
);

CREATE TABLE IF NOT EXISTS crawl.site_searches (
  brand_id integer NOT NULL REFERENCES crawl.brands (id),
  family text COLLATE "C" NOT NULL,
  searched_at timestamp without time zone NOT NULL,
  url text NOT NULL,
  PRIMARY KEY (brand_id, family)
);

-- the admin page: each brand's latest coverage. coverage_pct is null when no public list names the brand's models.
CREATE VIEW control.brand_coverage AS
SELECT c.id AS brand_id, c.name AS brand, v.measured_at, v.families, v.covered,
       CASE WHEN v.families > 0 THEN round(100.0 * v.covered / v.families, 1) END AS coverage_pct,
       v.by_category, v.phase, v.new_documents, v.gap_searches, v.site_searches
FROM control.brands c
JOIN LATERAL (SELECT * FROM crawl.coverage x WHERE x.brand_id = c.crawl_brand_id
              ORDER BY x.measured_at DESC, x.id DESC LIMIT 1) v ON true;

GRANT SELECT ON control.brand_coverage TO eq_runtime, eq_admin;
