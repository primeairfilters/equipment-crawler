-- Documents the code could not handle (user, 2026-10-29): one row per file and kind of problem, with what a fix needs
-- (the error, the reader's own message, page numbers, samples of the text read) and the version of the code part that
-- failed on it. The nightly run takes an open problem again once that part's version changes (a fix was made): read
-- again, tagged again or rebuilt; it is marked fixed with the version that fixed it, or stays open with the new
-- version. `./crawl issues` writes them all as one Markdown fix list, kept in control.issue_report for the admin page.
-- Additive: new tables, views and grants.
CREATE TABLE IF NOT EXISTS crawl.parse_issues (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_sha char(64) COLLATE "C" NOT NULL,
  document_id bigint NULL REFERENCES kb.documents (id),
  kind text NOT NULL CHECK (kind IN ('unreadable', 'cut_at_page_limit', 'mostly_scanned', 'garbled_text',
                                     'tagging_failed', 'no_sections')),
  component text NOT NULL CHECK (component IN ('reader', 'tagger', 'sectioner')),
  detail jsonb NOT NULL DEFAULT '{}',
  state text NOT NULL DEFAULT 'open' CHECK (state IN ('open', 'retrying', 'fixed', 'wont_fix')),
  first_version text NOT NULL,
  seen_version text NOT NULL,
  fixed_version text NULL,
  times_seen integer NOT NULL DEFAULT 1,
  first_seen_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  last_seen_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  fixed_at timestamp without time zone NULL,
  note text NULL,
  UNIQUE (content_sha, kind)
);
CREATE INDEX IF NOT EXISTS parse_issues_state ON crawl.parse_issues (state, kind);

-- which documents a scan-only check (garbled text) has looked at, under which reader: each is read once per version
CREATE TABLE IF NOT EXISTS crawl.issue_checks (
  document_id bigint NOT NULL REFERENCES kb.documents (id),
  check_name text NOT NULL,
  version text NOT NULL,
  checked_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  PRIMARY KEY (document_id, check_name)
);

CREATE TABLE IF NOT EXISTS control.issue_report (
  name text PRIMARY KEY,
  made_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  open_issues integer NOT NULL DEFAULT 0,
  markdown text NOT NULL
);

CREATE VIEW control.parse_issues AS
SELECT i.id, i.kind, i.component, i.state, i.document_id, d.title, m.name AS brand, i.content_sha,
       i.content_sha || '.pdf' AS original, d.page_count, i.detail, i.times_seen, i.first_seen_at, i.last_seen_at,
       i.first_version, i.seen_version, i.fixed_version, i.fixed_at, i.note
FROM crawl.parse_issues i
LEFT JOIN kb.documents d ON d.id = i.document_id
LEFT JOIN kb.manufacturers m ON m.id = d.manufacturer_id;

-- the page's buttons: set an open problem aside ("won't fix") or open it again, with a note
CREATE VIEW control.parse_issue_marks AS
SELECT id, state, note FROM crawl.parse_issues WHERE state IN ('open', 'wont_fix')
WITH CHECK OPTION;

GRANT SELECT, INSERT, UPDATE ON control.issue_report TO eq_runtime;
GRANT SELECT ON control.parse_issues, control.parse_issue_marks TO eq_runtime;
GRANT SELECT ON control.issue_report, control.parse_issues, control.parse_issue_marks TO eq_admin;
GRANT UPDATE (state, note) ON control.parse_issue_marks TO eq_admin;
